import { execFileSync } from 'node:child_process'
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { phrases } from '../src/data.ts'

// Requires FFmpeg with libflite and libmp3lame. Run after editing English phrases.
const temp = mkdtempSync(join(tmpdir(), 'budapest-voice-'))
try {
  const input = join(temp, 'phrase.txt')
  const clips = phrases.filter(([category]) => category !== 'ハンガリー語').map(([, , text]) => {
    const spokenText = text.replaceAll('’', "'")
      .replace(/Mangalica/gi, 'mahn-ga-lee-tsa')
      .replace(/foie gras/gi, 'fwah grah')
      .replace(/lángos/gi, 'lahn-gosh')
    writeFileSync(input, spokenText)
    const mp3 = execFileSync('ffmpeg', [
      '-hide_banner', '-loglevel', 'error', '-f', 'lavfi', '-i', `flite=textfile=${input}:voice=slt`,
      '-af', 'afade=t=in:d=0.02,volume=1.5,adelay=120,apad=pad_dur=0.12',
      '-ac', '1', '-c:a', 'libmp3lame', '-b:a', '24k', '-f', 'mp3', 'pipe:1',
    ])
    return [text, mp3.toString('base64')]
  })
  writeFileSync(new URL('../src/phrase-audio.ts', import.meta.url),
    '// Generated by scripts/phrase-audio.mjs.\nexport const phraseAudio = new Map<string, string>(' + JSON.stringify(clips, null, 2) + ')\n')
} finally {
  rmSync(temp, { recursive: true, force: true })
}
